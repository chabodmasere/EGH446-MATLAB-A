%% EGH446 Final Robustness Testing
% Runs the FINAL controller over multiple random missions and stores
% controller, guidance, estimator and ground-truth performance metrics.
%
% IMPORTANT:
% Model InitFcn should contain:
%
%   mdl_robot;
%   controller_params;
%
% Do NOT load fixed_waypoints.mat for robustness testing.


clear;
clc;
close all;


%% Settings

num_runs = 10;

% Simulink model name WITHOUT .slx
modelName = 'sl_groundvehicleDynamics';

% false = suppress full controller_analysis printout for every run
% true  = display full analysis for every run
show_detailed_run_output = false;


%% Preallocate Run Information

Run = (1:num_runs).';

% Initial conditions for traceability
StartX = nan(num_runs,1);
StartY = nan(num_runs,1);
StartHeadingDeg = nan(num_runs,1);

% Mission success
WaypointsPlanned = nan(num_runs,1);
WaypointsCaptured = nan(num_runs,1);
MissionSuccess = false(num_runs,1);


%% Preallocate Mission Performance

MissionTime = nan(num_runs,1);
RouteLength = nan(num_runs,1);
TimePerMetre = nan(num_runs,1);
EffectiveMissionSpeed = nan(num_runs,1);


%% Preallocate Heading Performance

ControllerRMSHeading = nan(num_runs,1);
ControllerMeanAbsHeading = nan(num_runs,1);
ControllerMaxHeading = nan(num_runs,1);

TrueRMSHeading = nan(num_runs,1);
TrueMeanAbsHeading = nan(num_runs,1);
TrueMaxHeading = nan(num_runs,1);


%% Preallocate Waypoint Capture Performance

EstimatedCaptureError = nan(num_runs,1);

TrueCaptureError = nan(num_runs,1);
TrueMaxCaptureError = nan(num_runs,1);
TrueMinCaptureError = nan(num_runs,1);


%% Preallocate Ground-Truth Cross-Track Performance

TrueRMSCrossTrack = nan(num_runs,1);
TrueMeanCrossTrack = nan(num_runs,1);
TrueMaxCrossTrack = nan(num_runs,1);


%% Preallocate Controller Command Performance

MeanVcmd = nan(num_runs,1);
MaxVcmd = nan(num_runs,1);

MeanAbsOmega = nan(num_runs,1);
MaxAbsOmega = nan(num_runs,1);


%% Preallocate Estimator Performance

EstimatorXRMSE = nan(num_runs,1);
EstimatorYRMSE = nan(num_runs,1);
EstimatorPositionRMSE = nan(num_runs,1);
EstimatorHeadingRMSE = nan(num_runs,1);


%% Preallocate Yaw Saturation Performance

YawSaturationTime = nan(num_runs,1);
YawSaturationPercent = nan(num_runs,1);


%% Archive Each Random Route
%
% These are stored in the MAT file so individual missions can be
% reconstructed later if required.

RouteArchive = cell(num_runs,1);
WaypointArchive = cell(num_runs,1);


%% Hide Figures During Automated Testing

oldFigureVisibility = ...
    get(groot,'defaultFigureVisible');

set(groot,'defaultFigureVisible','off');


%% Run Random Missions

try

    for run = 1:num_runs

        fprintf('\n');
        fprintf('========================================\n');
        fprintf('ROBUSTNESS RUN %d OF %d\n', ...
            run, num_runs);
        fprintf('========================================\n');


        %% Run Simulation
        %
        % The model InitFcn should execute:
        %
        %   mdl_robot;
        %   controller_params;
        %
        % Therefore each simulation should generate:
        %
        % - random initial X position
        % - random initial Y position
        % - random initial heading
        % - random waypoint set
        % - newly optimised waypoint order

        simOut = sim( ...
            modelName, ...
            'ReturnWorkspaceOutputs', ...
            'on');


        %% Retrieve Logged Signals

        logsout = ...
            simOut.get('logsout');


        %% Store Random Mission Information

        StartX(run) = ...
            robot.X;

        StartY(run) = ...
            robot.Y;

        StartHeadingDeg(run) = ...
            rad2deg(robot.Theta);

        WaypointsPlanned(run) = ...
            size(wp_ordered,1);


        % Store complete route for later reproduction / inspection
        RouteArchive{run} = ...
            wp_plot;

        WaypointArchive{run} = ...
            wp_ordered;


        %% Run Controller Analysis
        %
        % controller_analysis calculates all final performance metrics.
        %
        % evalc() can suppress the very long printed output while still
        % calculating all variables in this workspace.

        if show_detailed_run_output

            controller_analysis;

        else

            evalc('controller_analysis;');

        end


        %% Store Mission Results

        WaypointsCaptured(run) = ...
            num_true_waypoints_captured;

        MissionSuccess(run) = ...
            num_true_waypoints_captured == ...
            WaypointsPlanned(run);


        MissionTime(run) = ...
            mission_time;

        RouteLength(run) = ...
            route_length;

        TimePerMetre(run) = ...
            mission_time_per_metre;

        EffectiveMissionSpeed(run) = ...
            mission_effective_speed;


        %% Store Heading Results

        ControllerRMSHeading(run) = ...
            heading_error_rms;

        ControllerMeanAbsHeading(run) = ...
            heading_error_mean_abs;

        ControllerMaxHeading(run) = ...
            heading_error_max_abs;


        TrueRMSHeading(run) = ...
            true_heading_error_rms;

        TrueMeanAbsHeading(run) = ...
            true_heading_error_mean_abs;

        TrueMaxHeading(run) = ...
            true_heading_error_max_abs;


        %% Store Capture Results

        EstimatedCaptureError(run) = ...
            mean_capture_error;

        TrueCaptureError(run) = ...
            mean_true_capture_error;

        TrueMaxCaptureError(run) = ...
            max_true_capture_error;

        TrueMinCaptureError(run) = ...
            min_true_capture_error;


        %% Store Cross-Track Results

        TrueRMSCrossTrack(run) = ...
            rms_cross_track_error;

        TrueMeanCrossTrack(run) = ...
            mean_cross_track_error;

        TrueMaxCrossTrack(run) = ...
            max_cross_track_error;


        %% Store Controller Command Results

        MeanVcmd(run) = ...
            mean_v_cmd;

        MaxVcmd(run) = ...
            max_v_cmd;

        MeanAbsOmega(run) = ...
            mean_abs_omega_cmd;

        MaxAbsOmega(run) = ...
            max_omega_cmd;


        %% Store Estimator Results

        EstimatorXRMSE(run) = ...
            estimator_rmse_x;

        EstimatorYRMSE(run) = ...
            estimator_rmse_y;

        EstimatorPositionRMSE(run) = ...
            estimator_rmse_position;

        EstimatorHeadingRMSE(run) = ...
            estimator_rmse_heading;


        %% Store Yaw Saturation Results

        YawSaturationTime(run) = ...
            yaw_saturated_time;

        YawSaturationPercent(run) = ...
            yaw_saturation_percent;


        %% Short Run Summary

        fprintf( ...
            'Mission Time             = %.3f s\n', ...
            MissionTime(run));

        fprintf( ...
            'Route Length             = %.3f m\n', ...
            RouteLength(run));

        fprintf( ...
            'Time per Metre           = %.4f s/m\n', ...
            TimePerMetre(run));

        fprintf( ...
            'TRUE RMS Heading         = %.3f deg\n', ...
            TrueRMSHeading(run));

        fprintf( ...
            'TRUE RMS Cross-Track     = %.3f m\n', ...
            TrueRMSCrossTrack(run));

        fprintf( ...
            'TRUE Capture Error       = %.3f m\n', ...
            TrueCaptureError(run));

        fprintf( ...
            'Estimator Position RMSE  = %.3f m\n', ...
            EstimatorPositionRMSE(run));

        fprintf( ...
            'Estimator Heading RMSE   = %.3f deg\n', ...
            EstimatorHeadingRMSE(run));

        fprintf( ...
            'Yaw Saturation           = %.2f %%\n', ...
            YawSaturationPercent(run));

        fprintf( ...
            'Waypoints Captured       = %d/%d\n', ...
            WaypointsCaptured(run), ...
            WaypointsPlanned(run));

        fprintf( ...
            'RUN %d/%d COMPLETE\n', ...
            run, num_runs);

    end


catch ME

    % Restore figure visibility if a simulation or analysis fails
    set(groot, ...
        'defaultFigureVisible', ...
        oldFigureVisibility);

    close all;

    rethrow(ME);

end


%% Restore Figure Visibility

set(groot, ...
    'defaultFigureVisible', ...
    oldFigureVisibility);

close all;


%% Create Complete Individual-Run Results Table

results = table( ...
    Run, ...
    StartX, ...
    StartY, ...
    StartHeadingDeg, ...
    WaypointsPlanned, ...
    WaypointsCaptured, ...
    MissionSuccess, ...
    MissionTime, ...
    RouteLength, ...
    TimePerMetre, ...
    EffectiveMissionSpeed, ...
    ControllerRMSHeading, ...
    ControllerMeanAbsHeading, ...
    ControllerMaxHeading, ...
    TrueRMSHeading, ...
    TrueMeanAbsHeading, ...
    TrueMaxHeading, ...
    EstimatedCaptureError, ...
    TrueCaptureError, ...
    TrueMaxCaptureError, ...
    TrueMinCaptureError, ...
    TrueRMSCrossTrack, ...
    TrueMeanCrossTrack, ...
    TrueMaxCrossTrack, ...
    MeanVcmd, ...
    MaxVcmd, ...
    MeanAbsOmega, ...
    MaxAbsOmega, ...
    EstimatorXRMSE, ...
    EstimatorYRMSE, ...
    EstimatorPositionRMSE, ...
    EstimatorHeadingRMSE, ...
    YawSaturationTime, ...
    YawSaturationPercent);


%% Display Individual Run Results

fprintf('\n\n');
fprintf('========================================\n');
fprintf('FINAL ROBUSTNESS RESULTS\n');
fprintf('========================================\n\n');

disp(results);


%% Metrics Used for Statistical Analysis
%
% Initial X/Y/heading are recorded for traceability but are not
% performance metrics, so they are not included in this summary.

metric_names = { ...
    'MissionTime'; ...
    'RouteLength'; ...
    'TimePerMetre'; ...
    'EffectiveMissionSpeed'; ...
    'ControllerRMSHeading'; ...
    'ControllerMeanAbsHeading'; ...
    'ControllerMaxHeading'; ...
    'TrueRMSHeading'; ...
    'TrueMeanAbsHeading'; ...
    'TrueMaxHeading'; ...
    'EstimatedCaptureError'; ...
    'TrueCaptureError'; ...
    'TrueMaxCaptureError'; ...
    'TrueMinCaptureError'; ...
    'TrueRMSCrossTrack'; ...
    'TrueMeanCrossTrack'; ...
    'TrueMaxCrossTrack'; ...
    'MeanVcmd'; ...
    'MaxVcmd'; ...
    'MeanAbsOmega'; ...
    'MaxAbsOmega'; ...
    'EstimatorXRMSE'; ...
    'EstimatorYRMSE'; ...
    'EstimatorPositionRMSE'; ...
    'EstimatorHeadingRMSE'; ...
    'YawSaturationTime'; ...
    'YawSaturationPercent'};


metric_data = [ ...
    MissionTime, ...
    RouteLength, ...
    TimePerMetre, ...
    EffectiveMissionSpeed, ...
    ControllerRMSHeading, ...
    ControllerMeanAbsHeading, ...
    ControllerMaxHeading, ...
    TrueRMSHeading, ...
    TrueMeanAbsHeading, ...
    TrueMaxHeading, ...
    EstimatedCaptureError, ...
    TrueCaptureError, ...
    TrueMaxCaptureError, ...
    TrueMinCaptureError, ...
    TrueRMSCrossTrack, ...
    TrueMeanCrossTrack, ...
    TrueMaxCrossTrack, ...
    MeanVcmd, ...
    MaxVcmd, ...
    MeanAbsOmega, ...
    MaxAbsOmega, ...
    EstimatorXRMSE, ...
    EstimatorYRMSE, ...
    EstimatorPositionRMSE, ...
    EstimatorHeadingRMSE, ...
    YawSaturationTime, ...
    YawSaturationPercent];


%% Statistical Summary

Mean = ...
    mean(metric_data,1,'omitnan').';

StdDev = ...
    std(metric_data,0,1,'omitnan').';

Minimum = ...
    min(metric_data,[],1,'omitnan').';

Maximum = ...
    max(metric_data,[],1,'omitnan').';


% Coefficient of variation:
%
% CV = standard deviation / mean
%
% Useful for describing consistency between random missions.

CoVPercent = ...
    100 * StdDev ./ abs(Mean);

CoVPercent(abs(Mean) < eps) = ...
    NaN;


summary = table( ...
    metric_names, ...
    Mean, ...
    StdDev, ...
    Minimum, ...
    Maximum, ...
    CoVPercent, ...
    'VariableNames', ...
    { ...
    'Metric', ...
    'Mean', ...
    'StdDev', ...
    'Minimum', ...
    'Maximum', ...
    'CoVPercent' ...
    });


%% Display Statistical Summary

fprintf('\n');
fprintf('========================================\n');
fprintf('ROBUSTNESS STATISTICAL SUMMARY\n');
fprintf('========================================\n\n');

disp(summary);


%% Mission Success Statistics

successful_missions = ...
    sum(MissionSuccess);

total_waypoints_captured = ...
    sum(WaypointsCaptured, 'omitnan');

total_possible_waypoints = ...
    sum(WaypointsPlanned, 'omitnan');


mission_success_rate = ...
    100 * successful_missions / num_runs;


if total_possible_waypoints > 0

    waypoint_success_rate = ...
        100 * ...
        total_waypoints_captured / ...
        total_possible_waypoints;

else

    waypoint_success_rate = NaN;

end


fprintf('\n');
fprintf('Mission Success\n');
fprintf('---------------\n');

fprintf( ...
    'Successful Missions        = %d/%d\n', ...
    successful_missions, ...
    num_runs);

fprintf( ...
    'Mission Success Rate       = %.1f %%\n', ...
    mission_success_rate);

fprintf( ...
    'Waypoints Captured         = %d/%d\n', ...
    total_waypoints_captured, ...
    total_possible_waypoints);

fprintf( ...
    'Waypoint Success Rate      = %.1f %%\n', ...
    waypoint_success_rate);


%% Route Length vs Mission Time Correlation
%
% This helps determine whether differences in raw mission time are
% primarily caused by differences in randomly generated route length.

valid_corr = ...
    isfinite(RouteLength) & ...
    isfinite(MissionTime);


if sum(valid_corr) >= 2

    correlation_matrix = ...
        corrcoef( ...
        RouteLength(valid_corr), ...
        MissionTime(valid_corr));

    route_time_correlation = ...
        correlation_matrix(1,2);

else

    route_time_correlation = NaN;

end


fprintf('\n');
fprintf('Route / Mission-Time Relationship\n');
fprintf('---------------------------------\n');

fprintf( ...
    'Route-Time Correlation      = %.4f\n', ...
    route_time_correlation);


%% Final Report-Ready Summary

fprintf('\n');
fprintf('========================================\n');
fprintf('FINAL REPORT-READY ROBUSTNESS SUMMARY\n');
fprintf('========================================\n');

fprintf( ...
    'Mission Success             = %d/%d (%.1f %%)\n', ...
    successful_missions, ...
    num_runs, ...
    mission_success_rate);

fprintf( ...
    'Waypoint Success            = %d/%d (%.1f %%)\n', ...
    total_waypoints_captured, ...
    total_possible_waypoints, ...
    waypoint_success_rate);


fprintf( ...
    'Mission Time                = %.3f +/- %.3f s\n', ...
    mean(MissionTime,'omitnan'), ...
    std(MissionTime,'omitnan'));

fprintf( ...
    'Route Length                = %.3f +/- %.3f m\n', ...
    mean(RouteLength,'omitnan'), ...
    std(RouteLength,'omitnan'));

fprintf( ...
    'Mission Time per Metre      = %.4f +/- %.4f s/m\n', ...
    mean(TimePerMetre,'omitnan'), ...
    std(TimePerMetre,'omitnan'));

fprintf( ...
    'Effective Mission Speed     = %.3f +/- %.3f m/s\n', ...
    mean(EffectiveMissionSpeed,'omitnan'), ...
    std(EffectiveMissionSpeed,'omitnan'));


fprintf( ...
    'TRUE RMS Heading Error      = %.3f +/- %.3f deg\n', ...
    mean(TrueRMSHeading,'omitnan'), ...
    std(TrueRMSHeading,'omitnan'));

fprintf( ...
    'TRUE Capture Error          = %.3f +/- %.3f m\n', ...
    mean(TrueCaptureError,'omitnan'), ...
    std(TrueCaptureError,'omitnan'));

fprintf( ...
    'TRUE RMS Finite-Segment CT  = %.3f +/- %.3f m\n', ...
    mean(TrueRMSCrossTrack,'omitnan'), ...
    std(TrueRMSCrossTrack,'omitnan'));

fprintf( ...
    'TRUE Mean Finite-Segment CT = %.3f +/- %.3f m\n', ...
    mean(TrueMeanCrossTrack,'omitnan'), ...
    std(TrueMeanCrossTrack,'omitnan'));


fprintf( ...
    'Estimator Position RMSE     = %.3f +/- %.3f m\n', ...
    mean(EstimatorPositionRMSE,'omitnan'), ...
    std(EstimatorPositionRMSE,'omitnan'));

fprintf( ...
    'Estimator Heading RMSE      = %.3f +/- %.3f deg\n', ...
    mean(EstimatorHeadingRMSE,'omitnan'), ...
    std(EstimatorHeadingRMSE,'omitnan'));


fprintf( ...
    'Mean |omega_cmd|            = %.3f +/- %.3f rad/s\n', ...
    mean(MeanAbsOmega,'omitnan'), ...
    std(MeanAbsOmega,'omitnan'));

fprintf( ...
    'Yaw Saturation Percentage   = %.2f +/- %.2f %%\n', ...
    mean(YawSaturationPercent,'omitnan'), ...
    std(YawSaturationPercent,'omitnan'));


fprintf( ...
    'Route-Time Correlation      = %.4f\n', ...
    route_time_correlation);

fprintf('========================================\n');


%% Save Final Results

writetable( ...
    results, ...
    'robustness_results_final.csv');

writetable( ...
    summary, ...
    'robustness_summary_final.csv');


save( ...
    'robustness_results_final.mat', ...
    'results', ...
    'summary', ...
    'RouteArchive', ...
    'WaypointArchive', ...
    'route_time_correlation', ...
    'mission_success_rate', ...
    'waypoint_success_rate');


%% Save Final Controller Parameters for Traceability

final_controller_parameters = struct;

final_controller_parameters.K_theta = ...
    K_theta;

final_controller_parameters.K_dist = ...
    K_dist;

final_controller_parameters.v_max = ...
    v_max;

final_controller_parameters.omega_max = ...
    omega_max;

final_controller_parameters.heading_speed_min = ...
    heading_speed_min;

final_controller_parameters.rvwp_lookahead = ...
    rvwp_lookahead;

final_controller_parameters.capture_radius = ...
    capture_radius;


save( ...
    'robustness_results_final.mat', ...
    'final_controller_parameters', ...
    '-append');


%% Completion Message

fprintf('\n');
fprintf('Final robustness data saved to:\n');
fprintf('  robustness_results_final.csv\n');
fprintf('  robustness_summary_final.csv\n');
fprintf('  robustness_results_final.mat\n');

fprintf('\nFinal robustness testing complete.\n');